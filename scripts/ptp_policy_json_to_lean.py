#!/usr/bin/env python3
"""Render a PhaseTripleProduct banded-policy JSON as Lean modules for the PTP
suite `TableGeneration.RecursiveCost.PTP`.

Input: the sto_site band shape (one policy), mode must be PhaseTripleProduct:

    {"name": ..., "mode": "PhaseTripleProduct",
     "bands": [{"threshold": 2048, "k": 6, "point_order": [...],
                "operations": [...], "child_width": 398 (optional)}, ...]}

`child_width` (optional, per band) is a width the caller (e.g. the site's
pricing) assumes for that band at its own threshold; when present the
certificate proves it equals the PTP-derived child width, by `decide +kernel`.

Two modules: a data module (literals only) and a certificate module with
`accepted`, `chain_contracts` (scan mode only), `correct`, `correct_wrapped`, `width_sound`,
`gate_node`, `gate_recursion`, with --widths exact also `chain_contracts_exact`, `ladder_exact`,
`correct_exact`, `exact_minimal`, `exact_le_scan`, `exact_floor`, `gate_node_exact`, `gate_recursion_exact`,
and at the target N the threshold rule `chain_contracts_tight` (`chainContractsTight N`, which
replaces the scan `chain_contracts` in exact mode), `thresholds_at_target`, `correct_at_target`,
`exact_ladder_at_target`, `gate_recursion_exact_at_target`,
and per-band `child_width_<i>` when declared. Every proof is
`decide +kernel` or a one-line application of a generic theorem.

    ptp_policy_json_to_lean.py POLICY.json --module D --part data > D.lean
    ptp_policy_json_to_lean.py POLICY.json --module C --part cert --data-module D --target-width N > C.lean
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from policy_json_to_lean import IDENT, PolicyError, lean_comment, nat, op_lean, point_lean  # noqa: E402

NS = "TableGeneration.PTP.Instances"


def render(policy: dict, module: str, target: int | None, part: str, data_module: str | None = None,
           widths: str = "scan", exact_ladder: list | None = None) -> str:
    if not IDENT.match(module):
        raise PolicyError("module name must be a Lean identifier starting upper-case")
    if policy.get("mode") != "PhaseTripleProduct":
        raise PolicyError(f"mode must be PhaseTripleProduct, got {policy.get('mode')!r}")
    bands = policy.get("bands")
    if not isinstance(bands, list) or not bands:
        raise PolicyError("bands must be a nonempty list")
    out = []
    if part == "cert":
        if not data_module or not IDENT.match(data_module):
            raise PolicyError("--part cert needs --data-module NAME")
        out.append(f"import TableGeneration.RecursiveCost.PTP.Instances.{data_module}")
        out.append("import TableGeneration.RecursiveCost.PTP\n")
    else:
        out.append("import TableGeneration.RecursiveCost.PTP.Contract\n")
    name = lean_comment(policy.get('name', ''), 200)
    out.append(f"/-! Generated by scripts/ptp_policy_json_to_lean.py from: {name} -/\n")
    out.append(f"namespace {NS}.{module}\n")
    out.append("open TableGeneration TableGeneration.Operations TableGeneration.PTP\n")
    declared = []
    for bi, b in enumerate(bands):
        if b.get("mode", "PhaseTripleProduct") != "PhaseTripleProduct":
            raise PolicyError(f"band {bi} mode {b.get('mode')!r} is not PhaseTripleProduct")
        k = b.get("k")
        if not isinstance(k, int) or isinstance(k, bool) or k < 1:
            raise PolicyError(f"band {bi}: bad k {k!r}")
        thr = nat(b.get("threshold"))
        if "child_width" in b:
            declared.append((bi, thr, nat(b["child_width"])))
        if part == "cert":
            continue
        pts = [point_lean(p) for p in b.get("point_order", [])]
        ops = [op_lean(o, k) for o in b.get("operations", [])]
        out.append(f"/-- band {bi}: threshold {thr}, k = {k}, {len(pts)} points, {len(ops)} operations -/")
        out.append(f"def band{bi} : PTPTable where")
        out.append(f"  k := {k}")
        out.append("  pts := [" + ", ".join(pts) + "]")
        out.append("  ops :=")
        out.append(("    [ " + "\n    , ".join(ops) + " ]\n") if ops else "    []\n")
    if part != "cert":
        out.append("/-- The PTP policy: bands widest first. -/")
        out.append("def policy : PTPPolicy where")
        out.append("  bands := [" + ", ".join(f"⟨{nat(b['threshold'])}, band{i}⟩" for i, b in enumerate(bands)) + "]\n")
        out.append(f"end {NS}.{module}\n")
        return "\n".join(out)
    out.append(f"open {NS}.{data_module} Shor\n")
    out.append("/-- Acceptance: PTP check (sorted thresholds, every band passes the PTP contract), kernel-reduced. -/")
    out.append("theorem accepted : policy.check = true := by decide +kernel\n")
    if target is not None and widths == "scan":
        out.append(f"/-- Every band selected from width {target} strictly contracts under the PTP width scan. -/")
        out.append(f"theorem chain_contracts : policy.chainContracts {nat(target)} = true := by decide +kernel\n")
    for bi, thr, cw in declared:
        if widths == "exact":
            out.append(f"/-- Declared child width of band {bi} at its threshold equals the exact PTP width. -/")
            out.append(f"theorem child_width_{bi} : ptpTightWidth band{bi} {thr} = {cw} := by decide +kernel\n")
        else:
            out.append(f"/-- Declared child width of band {bi} at its threshold equals the PTP-derived one. -/")
            out.append(f"theorem child_width_{bi} : childWidth {thr} band{bi}.ops = {cw} := by decide +kernel\n")
    if widths == "exact":
        if target is not None:
            out.append(f"/-- Exact board: every band selected from width {target} contracts at its exact width. -/")
            out.append(f"theorem chain_contracts_exact : policy.chainContractsX {nat(target)} = true := by decide +kernel\n")
            if exact_ladder is not None:
                lad = ", ".join(f"({w}, {'some ' + str(kk) if kk is not None else 'none'})" for w, kk in exact_ladder)
                out.append(f"/-- The exact ladder from {target}, recomputed by the kernel. -/")
                out.append(f"theorem ladder_exact : policy.ladderX {nat(target)} = [{lad}] := by decide +kernel\n")
                N = nat(target)
                out.append(f"/-- The exact ladder from {N} (the literal of `ladder_exact`). -/")
                out.append(f"def exactLadder : List (ℕ × Option ℕ) := [{lad}]\n")
                out.append(f"/-- **Threshold acceptance rule** (exact widths): on the exact-width recursion from {N}, every chosen")
                out.append("band strictly shrinks the width and is applied at a width ≥ its k (non-degenerate limbs). The kernel")
                out.append("checks it on the pinned exact ladder. -/")
                out.append(f"theorem chain_contracts_tight : policy.chainContractsTight {N} = true := by")
                out.append("  unfold PTPPolicy.chainContractsTight")
                out.append("  rw [ladder_exact]")
                out.append("  decide +kernel\n")
                out.append(f"/-- The rule, stated without the ladder: every table chosen at every width the exact recursion from {N} reaches has k ≤ width and strictly shrinks it. -/")
                out.append(f"theorem thresholds_at_target : ∀ (m : ℕ) (T : PTPTable), policy.ExactReach {N} m →")
                out.append("    policy.choose m = some T → T.k ≤ m ∧ ptpTightWidth T m < m :=")
                out.append(f"  (PTPPolicy.chainContractsTight_iff_reach policy {N}).mp chain_contracts_tight\n")
                out.append(f"/-- Concrete correctness at the target width {N}: the exact board on operands fitting {N} signed bits. -/")
                out.append("theorem correct_at_target : ∀ (φ : ℚ) (x : Fin 3 → ℤ),")
                out.append(f"    (∀ s, FitsSignedWidth {N} (x s)) → policy.evalPhaseTight {N} φ x = φ * x 0 * x 1 * x 2 :=")
                out.append(f"  evalPhaseTight_correct policy accepted {N}\n")
                out.append(f"/-- The exact ladder at the target width {N}, and it passes the threshold rule. -/")
                out.append(f"theorem exact_ladder_at_target : policy.ladderX {N} = exactLadder ∧ policy.chainContractsTight {N} = true :=")
                out.append("  ⟨ladder_exact, chain_contracts_tight⟩\n")
                out.append(f"/-- Gate level at the target width {N}: `ptp_gate_full_exact` instantiated at n = {N}. -/")
                out.append("theorem gate_recursion_exact_at_target : ∀ (qs : QSemantics) [RegEncoding qs.Basis] [LowerGateClass qs]")
                out.append(f"    (X : Fin 3 → ExtReg) (base : ℕ), Good X {N} base →")
                out.append(f"    ∃ (W : List ℕ) (G : Angle → LowGate), PolicyImplX policy X {N} W G ∧")
                out.append(f"      (∀ q ∈ W, base ≤ q ∧ q < base + ptpWorkspaceX policy {N}) ∧")
                out.append(f"      (∀ (φ : Angle) (b : qs.Basis), (∀ s, FitsSignedWidth {N} (extToInt (X s) b)) →")
                out.append("        (∀ q ∈ W, RegEncoding.bit q b = false) →")
                out.append("        LowerGateClass.evalL (qs := qs) (G φ) (qs.ket b) =")
                out.append("          Complex.exp (((Angle.toReal φ : ℝ) : ℂ) * Complex.I *")
                out.append("            (((extToInt (X 0) b : ℤ) : ℂ) * ((extToInt (X 1) b : ℤ) : ℂ) *")
                out.append("              ((extToInt (X 2) b : ℤ) : ℂ))) • qs.ket b) ∧")
                out.append("      (∀ φ : Angle, let R := LowGate.resources shorGateResourceModel (G φ)")
                out.append(f"        R.rz = (ptpResourcesX policy {N}).rz ∧ R.toffoli = (ptpResourcesX policy {N}).toffoli ∧")
                out.append(f"          R.x = (ptpResourcesX policy {N}).x ∧ R.h = (ptpResourcesX policy {N}).h ∧")
                out.append(f"          R.cnot = ptpCnotFullX policy {N} ∧ adjToffCount (G φ) = ptpAndDagX policy {N} ∧")
                out.append(f"          (LowGate.usedQubits (G φ)).card ≤ 3 * {N} + ptpWorkspaceX policy {N}) :=")
                out.append(f"  fun _ _ _ X base hG => ptp_gate_full_exact policy accepted {N} X base hG\n")
        out.append("/-- (2) Exact board correct at every level: every node wraps at its exact width. -/")
        out.append("theorem correct_exact : ∀ (n : ℕ) (φ : ℚ) (x : Fin 3 → ℤ),")
        out.append("    (∀ s, FitsSignedWidth n (x s)) → policy.evalPhaseTight n φ x = φ * x 0 * x 1 * x 2 :=")
        out.append("  evalPhaseTight_correct policy accepted\n")
        out.append("/-- (3) Minimality: one bit below the exact width some reachable value does not fit. -/")
        out.append("theorem exact_minimal : ∀ b ∈ policy.bands, ∀ n : ℕ, 0 < n → ∃ x, FitsSignedWidth n x ∧")
        out.append("    ∃ v ∈ opTrace b.table n x, ¬ FitsSignedWidth (ptpTightWidth b.table n - 1) v :=")
        out.append("  fun b hb _ hn => tight_minimal b.table (PTPPolicy.check_tables accepted b hb) hn\n")
        out.append("/-- (4) The exact width never exceeds the PTP scan. -/")
        out.append("theorem exact_le_scan : ∀ b ∈ policy.bands, ∀ n : ℕ, 0 < n →")
        out.append("    ptpTightWidth b.table n ≤ childWidth n b.table.ops :=")
        out.append("  fun b hb _ hn => tight_le_childWidth b.table (PTPPolicy.check_tables accepted b hb) hn\n")
        out.append("/-- (5) No layout floor: the in-place split's floor (lower chunks + 1, top chunk) is implied by the exact width. -/")
        out.append("theorem exact_floor : ∀ b ∈ policy.bands, ∀ n : ℕ, exactWidth b.table n = ptpTightWidth b.table n :=")
        out.append("  fun b hb n => exactWidth_eq b.table (PTPPolicy.check_tables accepted b hb) n\n")
        out.append("/-- (c') Gate level, one node at ANY width ≥ the exact width (O5): sandwich-leaf children, pre-split slots, uncontrolled. -/")
        out.append("theorem gate_node_exact : ∀ b ∈ policy.bands, ∀ (qs : QSemantics) [RegEncoding qs.Basis] [LowerGateClass qs]")
        out.append("    (n : ℕ) (x : Fin 3 → ℤ), (∀ s, FitsSignedWidth n (x s)) → ∀ (Lay : NodeLayout b.table.k),")
        out.append("    ptpTightWidth b.table n ≤ Lay.width → ∀ (φ : Angle) (ta ua : ℕ), NodeAnc Lay ta ua →")
        out.append("    ∀ (bas : qs.Basis), AncClean ta ua bas →")
        out.append("    (∀ s i, extToInt (Lay.slot s i) bas = limbsAt b.table.k (limbWidth n b.table.k) (x s) i) →")
        out.append("    LowerGateClass.evalL (qs := qs) (ptpNode b.table Lay n φ ta ua) (qs.ket bas) =")
        out.append("      Complex.exp (((Angle.toReal φ : ℝ) : ℂ) * Complex.I *")
        out.append("        (((x 0 : ℤ) : ℂ) * ((x 1 : ℤ) : ℂ) * ((x 2 : ℤ) : ℂ))) • qs.ket bas :=")
        out.append("  fun b hb _ _ _ n x hx Lay hC φ ta ua hA bas hcl hbas =>")
        out.append("    evalL_ptpNode_ket_exact b.table (PTPPolicy.check_tables accepted b hb) n x hx Lay hC φ ta ua hA bas hcl hbas\n")
        out.append("/-- (d') Gate level, FULL recursion on the EXACT board (O5): for every width n and three pairwise disjoint n-qubit registers below `base`, a ForShor `LowGate` circuit following the policy with every node's children at `ptpTightWidth` (in-place split, zero/sign extension, table program, children, un-extension; sandwich leaves) is correct on every basis state with fitting operands and clean workspace, and its census is the exact-ladder formulas (Rz/Toffoli/X/H = ptpResourcesX, CNOT = ptpCnotFullX, And† = ptpAndDagX, qubits ≤ 3n + ptpWorkspaceX). Uncontrolled. -/")
        out.append("theorem gate_recursion_exact : ∀ (qs : QSemantics) [RegEncoding qs.Basis] [LowerGateClass qs]")
        out.append("    (n : ℕ) (X : Fin 3 → ExtReg) (base : ℕ), Good X n base →")
        out.append("    ∃ (W : List ℕ) (G : Angle → LowGate), PolicyImplX policy X n W G ∧")
        out.append("      (∀ q ∈ W, base ≤ q ∧ q < base + ptpWorkspaceX policy n) ∧")
        out.append("      (∀ (φ : Angle) (b : qs.Basis), (∀ s, FitsSignedWidth n (extToInt (X s) b)) →")
        out.append("        (∀ q ∈ W, RegEncoding.bit q b = false) →")
        out.append("        LowerGateClass.evalL (qs := qs) (G φ) (qs.ket b) =")
        out.append("          Complex.exp (((Angle.toReal φ : ℝ) : ℂ) * Complex.I *")
        out.append("            (((extToInt (X 0) b : ℤ) : ℂ) * ((extToInt (X 1) b : ℤ) : ℂ) *")
        out.append("              ((extToInt (X 2) b : ℤ) : ℂ))) • qs.ket b) ∧")
        out.append("      (∀ φ : Angle, let R := LowGate.resources shorGateResourceModel (G φ)")
        out.append("        R.rz = (ptpResourcesX policy n).rz ∧ R.toffoli = (ptpResourcesX policy n).toffoli ∧")
        out.append("          R.x = (ptpResourcesX policy n).x ∧ R.h = (ptpResourcesX policy n).h ∧")
        out.append("          R.cnot = ptpCnotFullX policy n ∧ adjToffCount (G φ) = ptpAndDagX policy n ∧")
        out.append("          (LowGate.usedQubits (G φ)).card ≤ 3 * n + ptpWorkspaceX policy n) :=")
        out.append("  fun _ _ _ n X base hG => ptp_gate_full_exact policy accepted n X base hG\n")
    out.append("/-- (a) Functional correctness: `φ · x₀ · x₁ · x₂` at every width. -/")
    out.append("theorem correct : ∀ (n : ℕ) (φ : ℚ) (x : Fin 3 → ℤ),")
    out.append("    policy.evalPhase n φ x = φ * x 0 * x 1 * x 2 :=")
    out.append("  evalPhase_correct policy accepted\n")
    out.append("/-- (a)+(b) Wrapping-register semantics, every node at its PTP child width. -/")
    out.append("theorem correct_wrapped : ∀ (n : ℕ) (φ : ℚ) (x : Fin 3 → ℤ),")
    out.append("    (∀ s, FitsSignedWidth n (x s)) → policy.evalPhaseW n φ x = φ * x 0 * x 1 * x 2 :=")
    out.append("  evalPhaseW_correct policy accepted\n")
    out.append("/-- (b) Register-width soundness of every band's node. -/")
    out.append("theorem width_sound : ∀ b ∈ policy.bands, ∀ (n : Fin 3 → ℕ), (∀ s, 0 < n s) →")
    out.append("    ∀ (x : Fin 3 → ℤ), (∀ s, FitsSignedWidth (n s) (x s)) → ∀ s : Fin 3,")
    out.append("      AllFits (childWidth3 n b.table.ops) (limbsAt b.table.k (limbWidth3 n b.table.k) (x s)) b.table.ops ∧")
    out.append("      (runF id (limbsAt b.table.k (limbWidth3 n b.table.k) (x s)) b.table.ops).1 =")
    out.append("        b.table.pts.map (fun p => regVal (expectedRow p) (limbsAt b.table.k (limbWidth3 n b.table.k) (x s))) ∧")
    out.append("      (∀ v ∈ (runF id (limbsAt b.table.k (limbWidth3 n b.table.k) (x s)) b.table.ops).1,")
    out.append("        FitsSignedWidth (childWidth3 n b.table.ops) v) ∧")
    out.append("      runF (tcWrapInt (childWidth3 n b.table.ops)) (limbsAt b.table.k (limbWidth3 n b.table.k) (x s)) b.table.ops =")
    out.append("        runF id (limbsAt b.table.k (limbWidth3 n b.table.k) (x s)) b.table.ops ∧")
    out.append("      (runF id (limbsAt b.table.k (limbWidth3 n b.table.k) (x s)) b.table.ops).2 =")
    out.append("        limbsAt b.table.k (limbWidth3 n b.table.k) (x s) :=")
    out.append("  fun b hb n hn x hx s => node_width_sound b.table (PTPPolicy.check_tables accepted b hb) n hn x hx s\n")
    out.append("/-- (c) Gate level, one recursion level: every band's node with **sandwich-leaf** children (compute–rotate–uncompute, two clean ancillas off the slots), uncontrolled, on pre-split slots of width ≥ the PTP child width, in ForShor's `LowGate`. Not the gate-level correctness of the whole policy. -/")
    out.append("theorem gate_node : ∀ b ∈ policy.bands, ∀ (qs : QSemantics) [RegEncoding qs.Basis] [LowerGateClass qs]")
    out.append("    (n : ℕ) (x : Fin 3 → ℤ), (∀ s, FitsSignedWidth n (x s)) → ∀ (Lay : NodeLayout b.table.k),")
    out.append("    childWidth n b.table.ops ≤ Lay.width → ∀ (φ : Angle) (ta ua : ℕ), NodeAnc Lay ta ua →")
    out.append("    ∀ (bas : qs.Basis), AncClean ta ua bas →")
    out.append("    (∀ s i, extToInt (Lay.slot s i) bas = limbsAt b.table.k (limbWidth n b.table.k) (x s) i) →")
    out.append("    LowerGateClass.evalL (qs := qs) (ptpNode b.table Lay n φ ta ua) (qs.ket bas) =")
    out.append("      Complex.exp (((Angle.toReal φ : ℝ) : ℂ) * Complex.I *")
    out.append("        (((x 0 : ℤ) : ℂ) * ((x 1 : ℤ) : ℂ) * ((x 2 : ℤ) : ℂ))) • qs.ket bas :=")
    out.append("  fun b hb _ _ _ n x hx Lay hC φ ta ua hA bas hcl hbas =>")
    out.append("    evalL_ptpNode_ket b.table (PTPPolicy.check_tables accepted b hb) n x hx Lay hC φ ta ua hA bas hcl hbas\n")
    out.append("/-- (d) Gate level, FULL recursion (O2): for every width n and three pairwise disjoint n-qubit registers below `base`, a ForShor `LowGate` circuit following the policy (in-place split, zero/sign extension into a reserve above `base`, table program, children, un-extension; sandwich leaves) is correct on every basis state with fitting operands and clean workspace, and its census is the policy formulas (Rz/Toffoli/X/H = ptpResources, CNOT = ptpCnotFull, And† = ptpAndDag, qubits ≤ 3n + ptpWorkspace). Uncontrolled. -/")
    out.append("theorem gate_recursion : ∀ (qs : QSemantics) [RegEncoding qs.Basis] [LowerGateClass qs]")
    out.append("    (n : ℕ) (X : Fin 3 → ExtReg) (base : ℕ), Good X n base →")
    out.append("    ∃ (W : List ℕ) (G : Angle → LowGate), PolicyImpl policy X n W G ∧")
    out.append("      (∀ q ∈ W, base ≤ q ∧ q < base + ptpWorkspace policy n) ∧")
    out.append("      (∀ (φ : Angle) (b : qs.Basis), (∀ s, FitsSignedWidth n (extToInt (X s) b)) →")
    out.append("        (∀ q ∈ W, RegEncoding.bit q b = false) →")
    out.append("        LowerGateClass.evalL (qs := qs) (G φ) (qs.ket b) =")
    out.append("          Complex.exp (((Angle.toReal φ : ℝ) : ℂ) * Complex.I *")
    out.append("            (((extToInt (X 0) b : ℤ) : ℂ) * ((extToInt (X 1) b : ℤ) : ℂ) *")
    out.append("              ((extToInt (X 2) b : ℤ) : ℂ))) • qs.ket b) ∧")
    out.append("      (∀ φ : Angle, let R := LowGate.resources shorGateResourceModel (G φ)")
    out.append("        R.rz = (ptpResources policy n).rz ∧ R.toffoli = (ptpResources policy n).toffoli ∧")
    out.append("          R.x = (ptpResources policy n).x ∧ R.h = (ptpResources policy n).h ∧")
    out.append("          R.cnot = ptpCnotFull policy n ∧ adjToffCount (G φ) = ptpAndDag policy n ∧")
    out.append("          (LowGate.usedQubits (G φ)).card ≤ 3 * n + ptpWorkspace policy n) :=")
    out.append("  fun _ _ _ n X base hG => ptp_gate_full policy accepted n X base hG\n")
    out.append(f"end {NS}.{module}\n")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("policy_json")
    ap.add_argument("--module", required=True)
    ap.add_argument("--target-width", type=int)
    ap.add_argument("--part", default="data", choices=["data", "cert"])
    ap.add_argument("--data-module")
    ap.add_argument("--widths", default="scan", choices=["scan", "exact"])
    a = ap.parse_args(argv)
    doc = json.loads(Path(a.policy_json).read_text())
    if "policy" in doc and "bands" not in doc:
        doc = doc["policy"]
    try:
        sys.stdout.write(render(doc, a.module, a.target_width, a.part, a.data_module, a.widths))
    except PolicyError as e:
        print(f"ptp_policy_json_to_lean: {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
