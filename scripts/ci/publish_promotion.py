#!/usr/bin/env python3
"""Commit a verified best-known generator straight to `main`.

The verification that makes this safe runs before this script does: the job
rebuilds the generator, repeats the trusted checks and reproduces every
promised metric. This script adds the last gate -- promotion may only touch
the paths `scripts/promote.py` generates -- and then pushes.
"""

from __future__ import annotations

import os
from pathlib import Path
import subprocess


# Deliberately spelled out here rather than imported from `scripts/promote.py`,
# which holds the same four paths as constants. This is the only gate between a
# promotion and `main`, so it has to be an independent opinion about what may be
# written: derived from `promote.py`, a bug that made it write the wrong path
# would also authorise it. The cost is that adding a generated file means
# editing both, and promotion fails until you do -- which is the safe direction.
REPORT_PATH = Path("leaderboard/best-known.md")
ALLOWED_FILES = {
    "TableGeneration/BestKnown.lean",
    str(REPORT_PATH),
    # Generated by scripts/promote.py alongside BestKnown.lean.
    "TableGeneration/RecursiveCost/ArchivedCatalog.lean",
}
ALLOWED_PREFIX = "TableGeneration/Policies/Accepted/"


def run(args: list[str], *, capture: bool = False) -> str:
    completed = subprocess.run(
        args,
        check=False,
        text=True,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.STDOUT if capture else None,
    )
    if completed.returncode != 0:
        raise RuntimeError(completed.stdout or f"command failed: {' '.join(args)}")
    # Preserve the leading columns in machine-readable `git status --short`
    # output; callers that parse JSON tolerate trailing whitespace.
    return (completed.stdout or "").rstrip("\n")


def changed_paths() -> list[str]:
    output = run(
        ["git", "status", "--short", "--untracked-files=all"],
        capture=True,
    )
    paths = []
    for line in output.splitlines():
        path = line[3:].strip()
        if " -> " in path:
            path = path.split(" -> ", 1)[1]
        paths.append(path)
    return paths


def allowed(path: str) -> bool:
    return path in ALLOWED_FILES or path.startswith(ALLOWED_PREFIX)


def report(sha: str) -> None:
    print(f"Promoted to main: {sha}")

    summary = os.getenv("GITHUB_STEP_SUMMARY", "").strip()
    if summary:
        with Path(summary).open("a", encoding="utf-8") as output:
            output.write(REPORT_PATH.read_text(encoding="utf-8"))
            output.write(f"\nPromoted to `main` as `{sha}`.\n")


def main() -> int:
    paths = changed_paths()
    disallowed = sorted(path for path in paths if not allowed(path))
    if disallowed:
        raise RuntimeError("promotion modified unexpected paths: " + ", ".join(disallowed))

    if not paths:
        print("Best-known generator is already current with main.")
        return 0

    run(["git", "config", "user.name", "github-actions[bot]"])
    run(
        [
            "git",
            "config",
            "user.email",
            "41898282+github-actions[bot]@users.noreply.github.com",
        ]
    )
    run(["git", "add", "--", *paths])
    run(["git", "commit", "-m", "feat: promote best-known table policies"])
    # This job fires on push to `main` and takes the better part of an hour, so
    # `main` may have moved since checkout. Only generated paths are touched and
    # nothing else writes them, so a rebase is safe; the ruleset forbids
    # non-fast-forward pushes, which this avoids.
    run(["git", "pull", "--rebase", "origin", "main"])
    run(["git", "push", "origin", "HEAD:main"])
    report(run(["git", "rev-parse", "--short", "HEAD"], capture=True).strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
